#!/usr/bin/env python3
"""Keep the original 32 px mode glyphs C/E/Q/S, with identical pixels/metrics."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "stm32_port/Core/lvgl/src/font/lv_font_montserrat_32.c"
DEST = ROOT / "stm32_port/Core/Src/dashboard_mode_font.c"


def generate():
    source = SOURCE.read_text()
    bitmap_source = re.search(r"glyph_bitmap\[\] = \{(.*?)\n\};", source, re.S)[1]
    bitmap_source = re.sub(r"/\*.*?\*/", "", bitmap_source, flags=re.S)
    bitmap = [int(byte, 16) for byte in re.findall(r"0x[0-9a-fA-F]+", bitmap_source)]
    descriptors = re.search(r"glyph_dsc\[\] = \{(.*?)\n\};", source, re.S)[1]
    descriptors = re.findall(r"\{([^{}]+)\}", descriptors)
    glyphs = []
    subset_bitmap = []
    for char in "CEQS":
        glyph = ord(char) - 0x20 + 1
        original = descriptors[glyph]
        start = int(re.search(r"bitmap_index = (\d+)", original)[1])
        end = int(re.search(r"bitmap_index = (\d+)", descriptors[glyph + 1])[1])
        metrics = dict((key, int(value)) for key, value in re.findall(r"\.(\w+) = (-?\d+)", original))
        assert end - start == (metrics["box_w"] * metrics["box_h"] + 1) // 2
        glyphs.append(re.sub(r"bitmap_index = \d+", f"bitmap_index = {len(subset_bitmap)}", original))
        subset_bitmap.extend(bitmap[start:end])
    data = "\n".join("    " + ", ".join(f"0x{byte:02x}" for byte in subset_bitmap[index:index + 12]) + ","
                     for index in range(0, len(subset_bitmap), 12))
    glyph_data = "\n".join("    {" + glyph + "}," for glyph in glyphs)
    return '''/* USER CODE BEGIN Mode_Font */
/* Generated by tools/subset_mode_font.py from LVGL Montserrat Medium 32.
 * C/E/Q/S are single-character mode labels; kerning is not needed.
 * Pixels, advance widths and baseline match the bundled full font. */
#include "../lvgl/lvgl.h"

static const uint8_t glyph_bitmap[] = {
''' + data + '''
};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {
    {0}, /* Reserved glyph ID 0. */
''' + glyph_data + '''
};
static const uint16_t unicode_list[] = {0, 2, 14, 16};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    .range_start = 67, .range_length = 17, .glyph_id_start = 1,
    .unicode_list = unicode_list, .list_length = 4,
    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .cmap_num = 1, .bpp = 4, .bitmap_format = 0
};
const lv_font_t dashboard_mode_font = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 35, .base_line = 6, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 2, .dsc = &font_dsc
};
/* USER CODE END Mode_Font */
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if DEST.read_text() != generated:
            raise SystemExit("Mode font is stale; run tools/subset_mode_font.py")
        print("Mode font: original pixel data and glyph metrics verified")
    else:
        DEST.write_text(generated)
        print(DEST)


if __name__ == "__main__":
    main()
