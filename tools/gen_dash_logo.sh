#!/usr/bin/env bash
# 把 tools/assets/BITFSAE.svg 栅格化为 A8(8 位透明度) C 数组 stm32_port/Core/Src/dash_logo.c。
# A8 由 LVGL 直接从 Flash 作遮罩绘制并按 recolor 着色, 不需要解码缓冲。
# 依赖 Node.js; @resvg/resvg-js 临时装到缓存目录。用法: tools/gen_dash_logo.sh [高度px, 默认29]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HEIGHT="${1:-29}"
CACHE="${XDG_CACHE_HOME:-$HOME/.cache}/hmi-dash-logo"
mkdir -p "$CACHE"
[ -d "$CACHE/node_modules/@resvg/resvg-js" ] || npm install --prefix "$CACHE" --no-save --silent @resvg/resvg-js@2
NODE_PATH="$CACHE/node_modules" node - "$ROOT/tools/assets/BITFSAE.svg" "$HEIGHT" \
    "$ROOT/stm32_port/Core/Src/dash_logo.c" <<'JS'
const {Resvg} = require('@resvg/resvg-js');
const fs = require('fs');
const [src, height, out] = process.argv.slice(2);
const img = new Resvg(fs.readFileSync(src, 'utf8'), {fitTo: {mode: 'height', value: +height}}).render();
const {width, pixels} = img, h = img.height;
const alpha = [];
for(let i = 3; i < pixels.length; i += 4) alpha.push(pixels[i]);
const rows = [];
for(let i = 0; i < alpha.length; i += 16) rows.push('    ' + alpha.slice(i, i + 16).map(v => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',');
fs.writeFileSync(out, `/* USER CODE BEGIN Dash_Logo */
/* Generated by tools/gen_dash_logo.sh from tools/assets/BITFSAE.svg, do not edit.
 * ${width}x${h} A8 coverage; drawn as a mask in the recolor colour. */
#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "../lvgl/lvgl.h"
#endif

static const uint8_t dash_logo_map[] = {
${rows.join('\n')}
};

const lv_image_dsc_t dash_logo = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_A8,
        .w = ${width},
        .h = ${h},
        .stride = ${width},
    },
    .data_size = sizeof(dash_logo_map),
    .data = dash_logo_map,
};
/* USER CODE END Dash_Logo */
`);
console.log(`dash_logo: ${width}x${h}, ${alpha.length} bytes`);
JS
