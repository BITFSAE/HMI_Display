#!/usr/bin/env bash
# 生成仪表盘字体 stm32_port/Core/Src/fonts/dash_font_*.c(固件与模拟器共用)。
# 依赖 Node.js;lv_font_conv 经 npx 拉取。字体: Barlow Semi Condensed(OFL, tools/fonts/),
# 图标取 LVGL 自带 FontAwesome。按需裁剪字符集, 4bpp 不压缩(LV_USE_FONT_COMPRESSED=0)。
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/stm32_port/Core/Src/fonts"
FONTS="$ROOT/tools/fonts"
FA="$ROOT/lvgl/scripts/built_in_font/FontAwesome5-Solid+Brands+Regular.woff"
CONV=(npx -y lv_font_conv@1.5.3)
ASCII="0x20-0x7E,0xB0"
mkdir -p "$OUT"

gen() { # name size weight [extra lv_font_conv args...]
    local name=$1 size=$2 weight=$3; shift 3
    "${CONV[@]}" --no-compress --bpp 4 --size "$size" --format lvgl \
        --font "$FONTS/BarlowSemiCondensed-$weight.ttf" "$@" \
        -o "$OUT/$name.c" --lv-font-name "$name"
    # 固件按相对路径引用 LVGL; 模拟器定义 LV_LVGL_H_INCLUDE_SIMPLE 用自身的 lvgl.h。
    # Opts 注释去掉本机绝对路径, 保证重新生成结果与机器无关。
    sed -i.bak -e 's|#include "lvgl/lvgl.h"|#include "../../lvgl/lvgl.h"|' \
        -e "s|$ROOT/||g" \
        -e '1s|^|/* USER CODE BEGIN Dash_Font */\n/* Generated by tools/gen_dash_fonts.sh, do not edit. */\n|' "$OUT/$name.c"
    printf '/* USER CODE END Dash_Font */\n' >> "$OUT/$name.c"
    rm -f "$OUT/$name.c.bak"
}

gen dash_font_speed 180 Bold     --symbols "0123456789-"
gen dash_font_xl    56  SemiBold --symbols "0123456789%-SQCE"
gen dash_font_l     36  SemiBold --symbols "0123456789:.+-"
gen dash_font_m     22  SemiBold -r "$ASCII"
gen dash_font_s     18  Medium   -r "$ASCII" --font "$FA" -r 0xF06E,0xF070,0xF0E7,0xF071
gen dash_font_xs    14  SemiBold -r "$ASCII"
